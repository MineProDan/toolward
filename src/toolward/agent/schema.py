"""Convert MCP tool definitions to the format Ollama's chat API expects.

MCP input schemas are generated by Pydantic, so they carry extra noise:
- every property has a "title" (and so does the whole schema),
- optional fields are written as {"anyOf": [{"type": X}, {"type": "null"}], "default": null}.

Ollama wants {"type": "function", "function": {"name", "description", "parameters"}}, where
parameters is a plain JSON schema object. We drop the titles, flatten "anyOf [X, null]" to X
(an optional field is simply left out of "required"), and keep enums, minimum/maximum, defaults
and descriptions.

Note: in ollama 0.6.3 (client) and Ollama 0.40.6 (server), only type, description and enum of a
property reach the model; minimum, maximum and default are dropped on the way. We still send them
so the definition stays complete, and the parameter descriptions state the ranges in words.
"""

from typing import Any


def _is_null(schema: dict) -> bool:
    return schema.get("type") == "null"


def convert_property(prop: dict[str, Any]) -> dict[str, Any]:
    """Clean one property schema: drop titles and flatten an optional anyOf."""
    out = {key: value for key, value in prop.items() if key not in ("title", "anyOf")}
    options = prop.get("anyOf")
    if options:
        non_null = [option for option in options if not _is_null(option)]
        if len(non_null) == 1:
            # anyOf [X, null] -> X. The inner schema's keys (type, enum, ...) move up.
            inner = convert_property(non_null[0])
            out = inner | out
        else:
            # Not a simple optional; keep the union as it is (titles removed).
            out["anyOf"] = [convert_property(option) for option in options]
    if out.get("default", "missing") is None:
        del out["default"]  # "default: null" just means "optional"
    return out


def convert_input_schema(schema: dict[str, Any]) -> dict[str, Any]:
    """Turn an MCP input schema into Ollama's "parameters" object."""
    properties = {
        name: convert_property(prop) for name, prop in schema.get("properties", {}).items()
    }
    parameters: dict[str, Any] = {"type": "object", "properties": properties}
    required = [name for name in schema.get("required", []) if name in properties]
    if required:
        parameters["required"] = required
    return parameters


def mcp_tool_to_ollama(name: str, description: str | None, input_schema: dict) -> dict:
    """One MCP tool -> one Ollama tool definition."""
    return {
        "type": "function",
        "function": {
            "name": name,
            "description": description or "",
            "parameters": convert_input_schema(input_schema),
        },
    }


def convert_tools(mcp_tools) -> list[dict]:
    """Convert the list returned by an MCP client's list_tools().tools."""
    return [mcp_tool_to_ollama(t.name, t.description, t.input_schema) for t in mcp_tools]
