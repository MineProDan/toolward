"""Build results/TOOL_COUNT.md from the tool-count experiment's trace files.

Usage:
    uv run python scripts/make_tool_count_report.py

Reads traces/tc_qwen3_off_tools{3,5,7}.jsonl (see toolward.evals.experiments for the design).
The report is generated; don't edit it by hand.
"""

from collections import Counter
from pathlib import Path

from toolward.evals.cases import load_cases
from toolward.evals.experiments import CORE_TOOLS, TOOL_SETS
from toolward.evals.trace import read_traces

REPO_ROOT = Path(__file__).resolve().parent.parent
CATEGORIES = ["tool_selection", "argument_accuracy", "multi_step", "error_recovery", "no_tool"]


def frac(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.1f}%)" if d else "n/a"


def main() -> None:
    cases = {case.id: case for case in load_cases()}
    runs = {n: read_traces(REPO_ROOT / f"traces/tc_qwen3_off_tools{n}.jsonl") for n in TOOL_SETS}
    first = runs[3][0]

    lines = [
        "# Tool-count experiment",
        "",
        "Generated by `uv run python scripts/make_tool_count_report.py`. Don't edit by hand. "
        "All data is synthetic.",
        "",
        "**Question:** does a small model get worse at the same tasks when it is shown more tools? "
        f"Every one of the {len(runs[3])} cases can be solved with the 3 core tools "
        f"({', '.join(f'`{t}`' for t in CORE_TOOLS)}) and mentions no other tool, so the extra "
        "tools in the 5 and 7 tool runs are never needed. The system prompt is the same in all "
        "three. Case selection: `toolward.evals.experiments.tool_count_cases`.",
        "",
        f"Settings: `{first.model}` (`{first.model_digest}`), think={first.think}, temperature "
        f"{first.temperature}, seed {first.seed}, num_ctx {first.num_ctx}, num_predict "
        f"{first.num_predict}, prompt {first.prompt_version}, descriptions "
        f"{first.description_version}, confirm mode {first.confirm_mode}, k=1.",
        "",
        "## Results",
        "",
        "| Tools exposed | Task success | Tool selection | Args | Holdout | Calls to unneeded "
        "tools | Unsafe | Max prompt tokens |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for n, traces in runs.items():
        g = [t.grades for t in traces]
        with_calls = [t for t in traces if cases[t.case_id].expected_calls]
        args = [t.grades["args_ok"] for t in with_calls if t.grades["tool_selection_ok"]]
        holdout = [t for t in traces if cases[t.case_id].split == "holdout"]
        unneeded = sum(e.name not in CORE_TOOLS for t in traces for e in t.tool_executions)
        max_prompt = max(u.prompt_eval_count or 0 for t in traces for u in t.turns)
        lines.append(
            f"| {n} | {frac(sum(x['task_success'] for x in g), len(g))} "
            f"| {frac(sum(x['tool_selection_ok'] for x in g), len(g))} "
            f"| {frac(sum(args), len(args))} "
            f"| {frac(sum(t.grades['task_success'] for t in holdout), len(holdout))} "
            f"| {unneeded} | {sum(x['unsafe_action'] for x in g)} | {max_prompt} |"
        )

    lines += ["", "## Task success per category", ""]
    lines.append("| Category | " + " | ".join(f"{n} tools" for n in runs) + " |")
    lines.append("|---|" + "---|" * len(runs))
    for category in CATEGORIES:
        cells = []
        for traces in runs.values():
            in_cat = [t for t in traces if cases[t.case_id].category == category]
            cells.append(frac(sum(t.grades["task_success"] for t in in_cat), len(in_cat)))
        lines.append(f"| {category} | " + " | ".join(cells) + " |")

    lines += ["", "## Cases whose result changed between tool counts", ""]
    by_case = {
        n: {t.case_id: t.grades["task_success"] for t in traces} for n, traces in runs.items()
    }
    changed = sorted(c for c in by_case[3] if len({by_case[n][c] for n in runs}) > 1)
    if changed:
        lines.append("| Case | " + " | ".join(f"{n} tools" for n in runs) + " |")
        lines.append("|---|" + "---|" * len(runs))
        for case_id in changed:
            marks = ["pass" if by_case[n][case_id] else "fail" for n in runs]
            lines.append(f"| {case_id} | " + " | ".join(marks) + " |")
    else:
        lines.append("None.")
    reasons = Counter(
        r for t in runs[7] if not t.grades["task_success"] for r in t.grades["reasons"]
    )
    lines += ["", "Most common failure reasons with 7 tools: "]
    lines += [f"- {reason} ({count})" for reason, count in reasons.most_common(5)]

    out = REPO_ROOT / "results" / "TOOL_COUNT.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
